// Package labrunner implements approval-bound orchestration outside the lab.
package labrunner

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"
)

// Plan contains every input reviewed by the operator. No defaults are applied
// after hashing. Driver contracts implement scenario-specific safety checks.
type Plan struct {
	PrivateEtcd      *PrivateEtcd `json:"private_etcd,omitempty"`
	Faults           []Fault      `json:"faults,omitempty"`
	Live             *LivePlan    `json:"live,omitempty"`
	Schema           int          `json:"schema"`
	RunID            string       `json:"run_id"`
	Stage            string       `json:"stage"`
	Created          time.Time    `json:"created"`
	Expires          time.Time    `json:"expires"`
	Profile          string       `json:"profile"`
	PreparedGuests   bool         `json:"prepared_guests"`
	Targets          []Target     `json:"targets"`
	Artifacts        []Artifact   `json:"artifacts"`
	Resources        []Resource   `json:"resources"`
	Budget           Budget       `json:"budget"`
	Disruptions      []string     `json:"disruptions"`
	Tests            []Selection  `json:"tests"`
	StateDir         string       `json:"state_dir"`
	EvidenceDir      string       `json:"evidence_dir"`
	PreserveFailures bool         `json:"preserve_failures"`
	Steps            []Step       `json:"steps"`
}

// Target records reviewed inventory, including initial state and version evidence.
type Target struct {
	Name         string `json:"name"`
	Host         string `json:"host"`
	Address      string `json:"address"`
	InitialState string `json:"initial_state"`
	Kernel       string `json:"kernel"`
	Packages     string `json:"packages"`
}

// Artifact pins a locally available executable or evidence input.
type Artifact struct {
	ID      string `json:"id"`
	Path    string `json:"path"`
	Version string `json:"version"`
	SHA256  string `json:"sha256"`
}

// Resource identifies a bounded disposable resource; reusable guests are targets.
type Resource struct {
	Name     string `json:"name"`
	Kind     string `json:"kind"`
	Target   string `json:"target"`
	Location string `json:"location"`
	MaxBytes int64  `json:"max_bytes"`
}

// Budget includes the entire window, including separate teardown allowances.
type Budget struct {
	GuestMemoryBytes   int64 `json:"guest_memory_bytes"`
	HostHeadroomBytes  int64 `json:"host_headroom_bytes"`
	CPUs               int   `json:"cpus"`
	DiskBytes          int64 `json:"disk_bytes"`
	IOBytes            int64 `json:"io_bytes"`
	ArtifactBytes      int64 `json:"artifact_bytes"`
	RetentionHours     int   `json:"retention_hours"`
	RuntimeSeconds     int   `json:"runtime_seconds"`
	CleanupSeconds     int   `json:"cleanup_seconds"`
	RestorationSeconds int   `json:"restoration_seconds"`
}

// Selection binds a test identifier and its deterministic seed.
type Selection struct {
	Name string `json:"name"`
	Seed int64  `json:"seed"`
}

// Step is either a pinned driver invocation or an allowlisted VM action.
// Drivers receive no implicit arguments or credentials. Contract is reviewed
// alongside the artifact; it must enforce resources and limits from the plan.
type Step struct {
	ID             string   `json:"id"`
	Phase          string   `json:"phase"`
	Test           string   `json:"test"`
	Action         string   `json:"action"`
	Artifact       string   `json:"artifact"`
	Args           []string `json:"args"`
	Contract       string   `json:"contract"`
	Effects        string   `json:"effects"`
	TimeoutSeconds int      `json:"timeout_seconds"`
	AppliesAfter   []string `json:"applies_after"`
	MaxAttempts    int      `json:"max_attempts"`
	Idempotent     bool     `json:"idempotent"`
}

// Approval is written explicitly by the operator, never generated by this tool.
type Approval struct {
	PlanHash   string    `json:"plan_hash"`
	Operator   string    `json:"operator"`
	ApprovedAt time.Time `json:"approved_at"`
	Statement  string    `json:"statement"`
}

// ReadJSON reads strict, bounded JSON and rejects trailing or unknown fields.
func ReadJSON(path string, value any) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer func() { _ = f.Close() }()
	d := json.NewDecoder(io.LimitReader(f, 4<<20))
	d.DisallowUnknownFields()
	if err := d.Decode(value); err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}
	var extra any
	if err := d.Decode(&extra); err != io.EOF {
		return fmt.Errorf("%s: expected exactly one JSON value", path)
	}
	return nil
}

// Hash returns a canonical SHA-256 over every typed plan field.
func (p Plan) Hash() (string, error) {
	if err := p.Validate(); err != nil {
		return "", err
	}
	b, err := json.Marshal(p)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:]), nil
}

// Validate rejects incomplete plans and unsupported lifecycle operations.
func (p Plan) Validate() error {
	if p.Stage == "stage2" {
		if p.PrivateEtcd != nil {
			return errors.New("private etcd is stage1 only")
		}
		if len(p.Faults) > 0 {
			return errors.New("native fault primitives are stage1 only")
		}
		return p.validateLive()
	}
	if p.Live != nil {
		return errors.New("live inputs require stage2")
	}
	if len(p.Steps) > 128 || len(p.Artifacts) > 128 || len(p.Resources) > 128 || len(p.Tests) > 128 {
		return errors.New("plan collections are limited to 128 entries each")
	}
	if p.Schema != 1 || p.Stage != "stage1" || !regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}$`).MatchString(p.RunID) {
		return errors.New("require schema 1, stage1, and a bounded run ID")
	}
	if !p.PreparedGuests || p.Profile == "" {
		return errors.New("only existing prepared guests are supported; profile is required")
	}
	if p.Created.IsZero() || !p.Expires.After(p.Created) || p.Expires.Sub(p.Created) > 24*time.Hour {
		return errors.New("plan validity must be positive and at most 24 hours")
	}
	if !cleanAbsolute(p.StateDir) || !cleanAbsolute(p.EvidenceDir) || p.StateDir == p.EvidenceDir {
		return errors.New("distinct absolute controller state/evidence directories required")
	}
	if p.Budget.GuestMemoryBytes != 6<<30 || p.Budget.HostHeadroomBytes < 4<<30 || p.Budget.CPUs != 6 || p.Budget.DiskBytes <= 0 || p.Budget.IOBytes <= 0 || p.Budget.ArtifactBytes <= 0 || p.Budget.RetentionHours <= 0 || p.Budget.RuntimeSeconds <= 0 || p.Budget.CleanupSeconds <= 0 || p.Budget.RestorationSeconds <= 0 || p.Budget.RuntimeSeconds > 86400 || p.Budget.CleanupSeconds > 86400 || p.Budget.RestorationSeconds > 86400 {
		return errors.New("complete positive budgets required; prepared guests use 6 GiB and six CPUs")
	}
	if len(p.Targets) != 5 {
		return errors.New("require exact f3 guest inventory including rocky and freebsd")
	}
	names := map[string]bool{}
	for _, t := range p.Targets {
		if names[t.Name] || t.Host != "f3" || t.Kernel == "" || t.Packages == "" {
			return errors.New("duplicate target or missing f3 inventory/version evidence")
		}
		names[t.Name] = true
		switch t.Name {
		case "hfs-test0", "hfs-test1", "hfs-test2":
			if t.InitialState != "Stopped" {
				return errors.New("prepared lifecycle currently requires initially stopped lab guests")
			}
		case "rocky":
			if t.InitialState != "Stopped" && t.InitialState != "Running" {
				return errors.New("unsupported Rocky initial state")
			}
		case "freebsd":
			if t.InitialState != "Stopped" {
				return errors.New("development FreeBSD VM must initially be stopped")
			}
		default:
			return errors.New("unsupported target")
		}
	}
	artifacts := map[string]Artifact{}
	for _, a := range p.Artifacts {
		if !validID(a.ID) || artifacts[a.ID].ID != "" || !cleanAbsolute(a.Path) || a.Version == "" || !regexp.MustCompile(`^[0-9a-f]{64}$`).MatchString(a.SHA256) {
			return errors.New("artifacts require unique IDs, absolute paths, versions and SHA-256")
		}
		artifacts[a.ID] = a
	}
	if len(p.Resources) == 0 || len(p.Tests) == 0 {
		return errors.New("bounded run resources and explicit test selections/seeds required")
	}
	var resourceBytes int64
	resourceNames := map[string]bool{}
	for _, r := range p.Resources {
		if r.MaxBytes > p.Budget.DiskBytes-resourceBytes {
			return errors.New("resource sizes exceed disk budget")
		}
		resourceBytes += r.MaxBytes
		if !validID(r.Name) || resourceNames[r.Name] || (!names[r.Target] && !isEtcdControllerResource(p, r)) || r.MaxBytes <= 0 || (r.Kind != "directory" && r.Kind != "dataset") || !p.validResource(r) {
			return errors.New("resources must name bounded disposable run-owned directories/datasets")
		}
		resourceNames[r.Name] = true
	}
	testNames := map[string]bool{}
	for _, t := range p.Tests {
		if !validID(t.Name) || testNames[t.Name] {
			return errors.New("test names must be unique explicit bounded identifiers")
		}
		testNames[t.Name] = true
	}
	if err := p.validateFaults(); err != nil {
		return err
	}
	if err := ValidatePrivateEtcd(p); err != nil {
		return err
	}
	return p.validateSteps(artifacts)
}

// CheckApproval binds explicit approval to the plan; recovery remains permitted
// after expiry so a stale run is not stranded with guests running.
func (p Plan) CheckApproval(a Approval, now time.Time, recovery bool) error {
	h, err := p.Hash()
	if err != nil {
		return err
	}
	if a.PlanHash != h || strings.TrimSpace(a.Operator) == "" || a.Statement != "I approve this exact plan" {
		return errors.New("explicit operator approval for this exact plan hash required")
	}
	if a.ApprovedAt.Before(p.Created) || a.ApprovedAt.After(p.Expires) || a.ApprovedAt.After(now) || (!recovery && (now.After(p.Expires) || now.Before(p.Created))) {
		return errors.New("stale or future plan/approval")
	}
	return nil
}

// VerifyArtifacts checks all bytes before any executor action.
func (p Plan) VerifyArtifacts() error {
	for _, a := range p.Artifacts {
		f, err := os.Open(a.Path)
		if err != nil {
			return err
		}
		h := sha256.New()
		_, copyErr := io.Copy(h, f)
		closeErr := f.Close()
		if copyErr != nil {
			return copyErr
		}
		if closeErr != nil {
			return closeErr
		}
		if hex.EncodeToString(h.Sum(nil)) != a.SHA256 {
			return fmt.Errorf("artifact changed: %s", a.ID)
		}
	}
	return nil
}

func (p Plan) validateSteps(artifacts map[string]Artifact) error {
	seen := map[string]string{}
	testCoverage := map[string]int{}
	for _, selection := range p.Tests {
		testCoverage[selection.Name] = 0
	}
	phaseOrder := map[string]int{"setup": 0, "test": 1, "collect": 2, "cleanup": 3, "restore": 4}
	last := -1
	counts := map[string]int{}
	totals := map[string]int{}
	for i, s := range p.Steps {
		order, ok := phaseOrder[s.Phase]
		if !ok || order < last || seen[s.ID] != "" || !validID(s.ID) || s.TimeoutSeconds <= 0 || s.TimeoutSeconds > 86400 || s.MaxAttempts < 1 || s.MaxAttempts > 3 {
			return errors.New("steps require unique IDs, positive deadlines, and ordered phases")
		}
		last = order
		allowance := s.TimeoutSeconds
		if s.Phase == "cleanup" || s.Phase == "restore" {
			allowance *= s.MaxAttempts
		}
		totals[s.Phase] += allowance
		if s.Contract == "" || artifacts[s.Artifact].ID == "" {
			return errors.New("every step requires a pinned artifact and reviewed contract")
		}
		if s.Phase == "test" {
			if _, selected := testCoverage[s.Test]; !selected || s.Action != "driver" {
				return errors.New("test-phase drivers must explicitly name a selected test")
			}
			testCoverage[s.Test]++
		} else if s.Test != "" {
			return errors.New("only test-phase drivers may claim selected test coverage")
		}
		switch s.Action {
		case "driver":
			if s.Effects != "read-only" && s.Effects != "run-owned" {
				return errors.New("driver effects must be read-only or run-owned")
			}
			if s.Phase == "collect" && s.Effects != "read-only" {
				return errors.New("collection must be read-only")
			}
		case "stop-rocky", "start-lab", "stop-lab", "start-rocky":
			if s.Effects != "lifecycle" {
				return errors.New("VM action must declare lifecycle effects")
			}
			if filepath.Base(artifacts[s.Artifact].Path) != "vms.sh" || len(s.Args) != 0 {
				return errors.New("VM lifecycle requires pinned vms.sh without custom arguments")
			}
			if (s.Action == "stop-rocky" || s.Action == "start-lab") && s.Phase != "setup" || s.Action == "stop-lab" && s.Phase != "cleanup" || s.Action == "start-rocky" && s.Phase != "restore" {
				return errors.New("VM action in unsafe phase")
			}
			if s.Action == "stop-rocky" && !contains(p.Disruptions, "rocky-downtime") {
				return errors.New("the Rocky downtime must be explicitly approved")
			}
		default:
			return fmt.Errorf("unsupported action %q: cloning/provisioning is not implemented", s.Action)
		}
		if i == 0 && (s.Action != "driver" || s.Phase != "setup" || s.Contract != "prepared-lab-preflight-v1" || s.Effects != "read-only") {
			return errors.New("first step must verify live inventory, initial states, memory/swap/disk, active users and pinned SSH keys using prepared-lab-preflight-v1")
		}
		if s.Phase == "cleanup" || s.Phase == "restore" {
			if !s.Idempotent || len(s.AppliesAfter) == 0 {
				return errors.New("teardown requires idempotence and explicit paired step IDs")
			}
			for _, id := range s.AppliesAfter {
				if seen[id] == "" || seen[id] == "cleanup" || seen[id] == "restore" {
					return errors.New("teardown pairing must refer to earlier forward steps")
				}
			}
		}
		seen[s.ID] = s.Phase
		counts[s.Action]++
	}
	for name, count := range testCoverage {
		if count == 0 {
			return fmt.Errorf("selected test %q has no test-phase driver step", name)
		}
	}
	if counts["start-lab"] != 1 || counts["stop-lab"] != 1 || counts["stop-rocky"] > 1 || counts["start-rocky"] > 1 {
		return errors.New("require exactly one paired lab startup/shutdown")
	}
	rockyRunning := false
	for _, t := range p.Targets {
		if t.Name == "rocky" {
			rockyRunning = t.InitialState == "Running"
		}
	}
	if rockyRunning && (counts["stop-rocky"] != 1 || counts["start-rocky"] != 1) || !rockyRunning && (counts["stop-rocky"] != 0 || counts["start-rocky"] != 0) {
		return errors.New("the Rocky stop/restore must exactly match reviewed initial state")
	}
	if totals["setup"]+totals["test"]+totals["collect"] > p.Budget.RuntimeSeconds || totals["cleanup"] > p.Budget.CleanupSeconds || totals["restore"] > p.Budget.RestorationSeconds {
		return errors.New("step deadlines exceed approved phase budgets")
	}
	for _, s := range p.Steps {
		if s.Action == "start-lab" && rockyRunning {
			earlier := false
			for _, x := range p.Steps {
				if x.ID == s.ID {
					break
				}
				earlier = earlier || x.Action == "stop-rocky"
			}
			if !earlier {
				return errors.New("stop Rocky before starting lab")
			}
		}
		if s.Action == "stop-lab" {
			paired := false
			for _, x := range p.Steps {
				paired = paired || x.Action == "start-lab" && contains(s.AppliesAfter, x.ID)
			}
			if !paired {
				return errors.New("lab shutdown must pair startup")
			}
		}
		if s.Action == "start-rocky" {
			paired := false
			for _, x := range p.Steps {
				paired = paired || x.Action == "stop-rocky" && contains(s.AppliesAfter, x.ID)
			}
			if !paired {
				return errors.New("the Rocky restoration must pair shutdown")
			}
		}
	}
	for _, s := range p.Steps {
		if s.Action == "driver" && s.Effects == "run-owned" && (s.Phase == "setup" || s.Phase == "test") {
			paired := false
			for _, c := range p.Steps {
				paired = paired || c.Phase == "cleanup" && contains(c.AppliesAfter, s.ID)
			}
			if !paired {
				return errors.New("every mutating driver requires paired cleanup")
			}
		}
	}
	return nil
}

func (p Plan) validResource(r Resource) bool {
	if r.Kind == "directory" {
		root := "/var/tmp/hfs-run-" + p.RunID
		return filepath.Clean(r.Location) == r.Location && (r.Location == root || strings.HasPrefix(r.Location, root+"/"))
	}
	for i := 0; i < 3; i++ {
		if r.Target != fmt.Sprintf("hfs-test%d", i) {
			continue
		}
		for _, area := range []string{"data", "journal", "control"} {
			root := fmt.Sprintf("hfsdata%d/%s/hfs-run-%s", i, area, p.RunID)
			if r.Location == root || strings.HasPrefix(r.Location, root+"/") && !strings.Contains(r.Location, "..") {
				return true
			}
		}
	}
	return false
}
func validID(s string) bool {
	return regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}$`).MatchString(s)
}
func cleanAbsolute(s string) bool { return filepath.IsAbs(s) && filepath.Clean(s) == s && s != "/" }
func contains(ss []string, s string) bool {
	for _, x := range ss {
		if x == s {
			return true
		}
	}
	return false
}
